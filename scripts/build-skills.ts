import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT_DIR = join(__dirname, "..");
const SKILLS_DIR = join(ROOT_DIR, "skills");
const OUTPUT_FILE = join(ROOT_DIR, "apps/api/src/skills.generated.ts");

interface SkillData {
  description: string;
  body: string;
}

function parseSkillFile(filePath: string, folderName: string): SkillData {
  const content = readFileSync(filePath, "utf-8");
  const lines = content.split("\n");

  if (!lines[0]?.startsWith("---")) {
    throw new Error(`Missing front matter in ${filePath}`);
  }

  const endIndex = lines.findIndex((line, i) => i > 0 && line === "---");
  if (endIndex === -1) {
    throw new Error(`Unclosed front matter in ${filePath}`);
  }

  const frontMatter = lines.slice(1, endIndex);
  let name: string | undefined;
  let description: string | undefined;

  for (const line of frontMatter) {
    if (line.startsWith("name:")) {
      name = line.slice(5).trim();
    } else if (line.startsWith("description:")) {
      description = line.slice(12).trim();
    }
  }

  if (!name) {
    throw new Error(`Missing name in front matter of ${filePath}`);
  }
  if (name !== folderName) {
    throw new Error(`Name "${name}" does not match folder "${folderName}" in ${filePath}`);
  }
  if (!description) {
    throw new Error(`Missing description in front matter of ${filePath}`);
  }

  const body = lines.slice(endIndex + 1).join("\n").trim();

  return { description, body };
}

function buildSkills() {
  const folders = readdirSync(SKILLS_DIR, { withFileTypes: true });
  const skills: Record<string, SkillData> = {};

  for (const entry of folders) {
    if (!entry.isDirectory() || entry.name.startsWith(".")) continue;
    const skillFile = join(SKILLS_DIR, entry.name, "SKILL.md");
    const skill = parseSkillFile(skillFile, entry.name);
    skills[entry.name] = skill;
  }

  const output = `// Generated by scripts/build-skills.ts. Do not edit.
export const SKILLS: Record<string, { description: string; body: string }> = ${JSON.stringify(
  skills,
  null,
  2,
)};
`;

  writeFileSync(OUTPUT_FILE, output, "utf-8");
  console.log(`Wrote ${Object.keys(skills).length} skills to ${OUTPUT_FILE}`);
}

buildSkills();
